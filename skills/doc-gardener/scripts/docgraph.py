# ---------------------------------------------------------------- basics

def inside(root: Path, path: Path) -> bool:
    return path == root or root in path.parents


def rel(path: Path, root: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return str(path)


def issue(kind: str, file: str, line: int, message: str, target: str | None = None) -> dict:
    item = {'type': kind, 'file': file, 'line': line, 'message': message}
    if target is not None:
        item['target'] = target
    return item


def globmatch(path: str, pattern: str) -> bool:
    pattern = pattern.rstrip('/')
    if pattern in ('.', ''):
        return True
    parts = path.split('/')
    return any(fnmatch.fnmatchcase('/'.join(parts[:i]), pattern)
               for i in range(1, len(parts) + 1))


def is_doc(path: str) -> bool:
    return path.lower().endswith(DOC_EXT)


def standalone(path: str) -> bool:
    return Path(path).stem.lower() in STANDALONE_STEMS or path.startswith('.github/')


def config(root: Path) -> dict:
    path = root / '.doc-gardener.json'
    if not path.is_file():
        return {}
    data = json.loads(path.read_text(encoding='utf-8'))
    if not isinstance(data, dict):
        raise ValueError('.doc-gardener.json must be a JSON object')
    for name in ('include', 'exclude', 'entrypoints', 'allow_orphans', 'mappings', 'policy_exclude', 'code_ref_ignore'):
        if name in data and not isinstance(data[name], list):
            raise ValueError(f'.doc-gardener.json: {name} must be an array')
    for rule in data.get('mappings', []):
        if not isinstance(rule, dict) or not isinstance(rule.get('code'), str) or not isinstance(rule.get('docs', []), list):
            raise ValueError('.doc-gardener.json: each mapping needs "code" (glob) and "docs" (array)')
    if data.get('metadata_profile', 'none') not in ('none', 'doc-gardener'):
        raise ValueError('.doc-gardener.json: metadata_profile must be none or doc-gardener')
    return data


# ---------------------------------------------------------------- file discovery

def git_files(root: Path) -> list[str] | None:
    """Tracked + untracked-but-not-ignored files relative to root, or None outside git."""
    try:
        ret = subprocess.run(['git', '-C', str(root), 'ls-files', '-z', '--cached', '--others', '--exclude-standard'],
                             capture_output=True, check=False)
    except OSError:
        return None
    if ret.returncode:
        return None
    # Entries ending in "/" are nested repositories/worktrees: not part of this knowledge base.
    return [p for p in ret.stdout.decode('utf-8', 'replace').split('\0') if p and not p.endswith('/')]


def walk_files(root: Path) -> list[str]:
    out = []
    for base, dirs, files in os.walk(root):
        basepath = Path(base)
        dirs[:] = [d for d in dirs if d not in SKIP and not (basepath / d).is_symlink()
                   and not (basepath / d / '.git').exists()]
        out.extend((basepath / f).relative_to(root).as_posix() for f in files)
    return out


def repo_files(root: Path) -> list[str]:
    files = git_files(root)
    if files is None:
        files = walk_files(root)
    result = []
    nested: dict[str, bool] = {}

    def in_nested_repo(r: str) -> bool:
        parts = r.split('/')[:-1]
        for i in range(1, len(parts) + 1):
            d = '/'.join(parts[:i])
            if d not in nested:
                nested[d] = (root / d / '.git').exists()
            if nested[d]:
                return True
        return False

    for r in files:
        if any(part in SKIP for part in r.split('/')[:-1]) or in_nested_repo(r):
            continue
        p = root / r
        if p.is_symlink() or not p.is_file():
            continue
        result.append(r)
    return sorted(set(result))


def discover(root: Path, selected: list[str], cfg: dict, files: list[str] | None = None) -> list[Path]:
    """All Markdown in the repository (git-aware), narrowed by include/--docs and exclude."""
    include = selected or cfg.get('include', [])
    if not all(isinstance(x, str) for x in include):
        raise ValueError('include/--docs must contain strings')
    exclude = cfg.get('exclude', [])
    result = []
    for r in files if files is not None else repo_files(root):
        if not is_doc(r) or any(globmatch(r, x) for x in exclude):
            continue
        if include and not any(globmatch(r, x) for x in include):
            continue
        result.append((root / r).resolve())
    return sorted(set(result))


# ---------------------------------------------------------------- markdown parsing

def mask_source(text: str, keep_inline: bool = False) -> list[str]:
    """Blank frontmatter, fenced code, HTML comments (and inline code unless keep_inline).

    Line count and in-line character positions are preserved, so match offsets on the
    masked text are valid offsets on the original text.
    """
    raw = text.splitlines()
    result = []
    front_end = -1
    if raw and raw[0].lstrip('﻿').strip() == '---':
        for j in range(1, min(len(raw), 300)):
            if raw[j].strip() in ('---', '...'):
                front_end = j
                break
    active_fence = ''
    comment = False
    for idx, line in enumerate(raw):
        if idx <= front_end:
            result.append('')
            continue
        match = FENCE.match(line)
        if match:
            delim = match.group(1)
            if not active_fence:
                active_fence = delim
                result.append('')
                continue
            if active_fence[0] == delim[0] and len(delim) >= len(active_fence):
                active_fence = ''
                result.append('')
                continue
        if active_fence:
            result.append('')
            continue
        chars = list(line)
        i = 0
        while i < len(chars):
            if comment:
                end = line.find('-->', i)
                last = len(chars) if end == -1 else end + 3
                for j in range(i, last):
                    chars[j] = ' '
                if end == -1:
                    i = len(chars)
                else:
                    comment = False
                    i = last
                continue
            start = line.find('<!--', i)
            if start == -1:
                break
            comment = True
            i = start
        cleaned = ''.join(chars)
        if not keep_inline:
            cleaned = INLINE_CODE.sub(lambda m: ' ' * len(m.group(0)), cleaned)
        result.append(cleaned)
    return result


def slug(text: str) -> str:
    """GitHub-style heading id (github-slugger semantics, approximately)."""
    text = re.sub(r'<[^>]*>', '', text)
    text = re.sub(r'!?\[([^]]*)\]\([^)]*\)', r'\1', text)
    text = text.replace('`', '').replace('*', '')
    # Underscores used as emphasis vanish; underscores inside words (snake_case) are kept.
    text = re.sub(r'(?<![^\W_])_+|_+(?![^\W_])', '', text)
    text = text.strip().lower()
    text = ''.join(c for c in text if c.isalnum() or c in (' ', '-', '_'))
    return text.replace(' ', '-')


def _paragraph_line(line: str) -> bool:
    return bool(line.strip()) and not line.startswith('    ') and not re.match(
        r'^\s{0,3}([>|#<]|[-*+]\s|\d+[.)]\s|(=+|-+)\s*$)', line)


def headings(lines: list[str]) -> list[tuple[int, int, str]]:
    """(line number, level, text) for ATX and setext headings."""
    out = []
    prev = ''
    for n, line in enumerate(lines, 1):
        m = HEADING.match(line)
        if m:
            out.append((n, len(m.group(1)), m.group(2)))
            prev = ''
            continue
        s = SETEXT.match(line)
        if s and _paragraph_line(prev):
            out.append((n - 1, 1 if s.group(1)[0] == '=' else 2, prev.strip()))
            prev = ''
            continue
        prev = line
    return out


def heading_anchors(lines: list[str]) -> set[str]:
    seen = Counter()
    out = set()
    for _, _, s in headings(lines):
        custom = re.search(r'\s*\{#([\w-]+)\}\s*$', s)
        if custom:
            out.add(custom.group(1))
            s = s[:custom.start()]
        key = slug(s)
        count = seen[key]
        seen[key] += 1
        out.add(key if count == 0 else f'{key}-{count}')
    for line in lines:
        out.update(HTML_ID.findall(line))
        block = BLOCK_ID.search(line)
        if block:
            out.add('^' + block.group(1))
    return out


def has_anchor(anchors: set[str], anchor: str) -> bool:
    # Exact id, case-folded id, or heading text (Obsidian-style [[page#Heading text]]).
    return anchor in anchors or anchor.lower() in anchors or slug(anchor) in anchors


def existing(dest: Path) -> Path | None:
    """Resolve a link target; extensionless page links are common (Docusaurus, VitePress, Obsidian)."""
    if dest.exists():
        return dest
    if not dest.suffix or dest.suffix.lower() not in DOC_EXT:
        for ext in DOC_EXT:
            cand = dest.with_name(dest.name + ext)
            if cand.exists():
                return cand
    return None


def href(raw: str) -> str:
    raw = raw.strip()
    if raw.startswith('<') and '>' in raw:
        raw = raw[1:raw.index('>')]
    else:
        raw = re.split(r'\s+["\'(]', raw, maxsplit=1)[0]
    return re.sub(r'\\([ ()])', r'\1', raw)


def is_remote(value: str) -> bool:
    return bool(re.match(r'^[a-zA-Z][a-zA-Z0-9+.-]*:', value)) or value.startswith('//')


def link_spans(line: str):
    """(start, end, raw destination) for inline links and reference definitions."""
    for m in LINK.finditer(line):
        yield m.start(1), m.end(1), m.group(1)
    ref = REFDEF.match(line)
    if ref:
        yield ref.start(2), ref.end(2), ref.group(2)


def resolve(root: Path, source: Path, pathname: str) -> Path:
    return (root / pathname.lstrip('/') if pathname.startswith('/') else source.parent / pathname).resolve()


def frontmatter(content: str) -> dict[str, str]:
    """Read plain scalar YAML frontmatter fields; not a general YAML parser."""
    normalized = content.lstrip('﻿')
    match = FRONT.match(normalized)
    if not match:
        return {}
    data = {}
    for line in match.group(1).splitlines():
        m = META_KEY.match(line)
        if m:
            value = m.group(2).strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in ('"', "'"):
                value = value[1:-1]
            data[m.group(1)] = value
    return data


def looks_like_path(token: str) -> str | None:
    """Return a normalized repo path if an inline-code token looks like one, else None."""
    token = token.strip()
    token = re.sub(r'(:\d+(-\d+)?|#L\d+(-L?\d+)?)$', '', token)
    if (not token or len(token) > 200 or ' ' in token or token.startswith(('/', '~', '-', 'path/to/', 'path/like'))
            or is_remote(token) or any(c in token for c in '<>{}[]*$%?|\\"\'=,;:@')):
        return None
    token = token.removeprefix('./')
    if '/' not in token.rstrip('/'):
        return None
    last = token.rstrip('/').rsplit('/', 1)[-1]
    if token.endswith('/') or re.search(r'\.[A-Za-z][A-Za-z0-9]{0,9}$', last):
        return token
    return None


def resolve_code_ref(root: Path, source: Path, token: str, with_base: bool = False):
    """Try the page's folder and each ancestor up to the root (package-relative paths)."""
    base = source.parent
    while True:
        cand = (base / token).resolve()
        if inside(root, cand) and cand.exists():
            return (cand, base) if with_base else cand
        if base == root or root not in base.parents:
            return None
        base = base.parent


def words(text: str) -> list[str]:
    return [w.lower() for w in WORD.findall(text)]


# ---------------------------------------------------------------- policy

def check_page_policy(root: Path, path: Path, content: str, lines: list[str], cfg: dict) -> tuple[list[dict], str | None]:
    """Optional adoption checks, warnings only for legacy docs."""
    r = rel(path, root)
    excluded = cfg.get('policy_exclude', [])
    if any(globmatch(r, pattern) for pattern in excluded):
        return [], None
    if path.name.lower() in ENTRY_NAMES or path.name.lower() in {'changelog.md', 'license.md'}:
        return [], None
    metadata = frontmatter(content)
    items = []
    # Project-agnostic default: only inspect the ID if the repo already uses one.
    # Do NOT require Doc Gardener's optional example frontmatter in arbitrary repos.
    if cfg.get('metadata_profile', 'none') != 'doc-gardener':
        return items, metadata.get('id')
    for key in ('id', 'title', 'summary', 'kind', 'status'):
        if not metadata.get(key):
            items.append(issue('missing_metadata', r, 1, f'Missing frontmatter {key}'))
    if metadata.get('id') and not re.fullmatch(r'[a-z0-9][a-z0-9-]*', metadata['id']):
        items.append(issue('invalid_doc_id', r, 1, f'Invalid document id: {metadata["id"]}'))
    if metadata.get('kind') and metadata['kind'] not in VALID_KINDS:
        items.append(issue('invalid_kind', r, 1, f'Unknown kind: {metadata["kind"]}'))
    if metadata.get('status') and metadata['status'] not in VALID_STATUSES:
        items.append(issue('invalid_status', r, 1, f'Unknown status: {metadata["status"]}'))
    first_title = next((t for _, level, t in headings(lines) if level == 1), '')
    if not first_title:
        items.append(issue('missing_heading', r, 1, 'Expected an H1 title'))
    elif metadata.get('title') and first_title.strip() != metadata['title']:
        items.append(issue('title_mismatch', r, 1, 'Frontmatter title differs from first heading'))
    if metadata.get('kind') in {'concept', 'architecture'} and not any(
            line.strip().lower() == '## relationships' for line in lines):
        items.append(issue('missing_relationships', r, 1, 'Add a Relationships section with typed links when meaningful'))
    return items, metadata.get('id')


def extract_relations(lines: list[str], source: Path, root: Path, docset: set[Path]) -> dict[str, list[str]]:
    """Extract explicitly typed Markdown doc links within ## Relationships."""
    found: dict[str, set[str]] = defaultdict(set)
    in_section = False
    for line in lines:
        if re.match(r'^##\s+Relationships\s*$', line, re.I):
            in_section = True
            continue
        if in_section and re.match(r'^#{1,2}\s+', line):
            in_section = False
        if not in_section:
            continue
        m = RELATION.match(line)
        if not m:
            continue
        kind = m.group(1).lower().replace(' ', '_')
        for match in LINK.finditer(line):
            address = href(match.group(1))
            if not address or is_remote(address):
                continue
            pathname = unquote(urlsplit(address).path)
            if not pathname:
                continue
            target = resolve(root, source, pathname)
            if target in docset and target != source:
                found[kind].add(rel(target, root))
    return {kind: sorted(targets) for kind, targets in sorted(found.items())}


# ---------------------------------------------------------------- graph build / check

def _sections(lines: list[str]) -> list[tuple[int, str, str]]:
    """(start line, heading, body text) per heading-delimited section."""
    marks = headings(lines)
    out = []
    bounds = [(1, '')] + [(n, t) for n, _, t in marks]
    for i, (start, title) in enumerate(bounds):
        end = bounds[i + 1][0] - 1 if i + 1 < len(bounds) else len(lines)
        body = '\n'.join(lines[start:end] if title else lines[0:end])
        out.append((start, title, body))
    return out


def _near_duplicates(shingles: dict[str, set[int]], exact: set[frozenset], threshold=0.7) -> list[tuple[str, str, float]]:
    postings: dict[int, list[str]] = defaultdict(list)
    for doc, sh in shingles.items():
        for h in sh:
            postings[h].append(doc)
    shared: Counter = Counter()
    for docs in postings.values():
        if 1 < len(docs) <= 25:  # very common shingles carry no signal
            for i, a in enumerate(docs):
                for b in docs[i + 1:]:
                    shared[(a, b)] += 1
    out = []
    for (a, b), n in shared.items():
        if frozenset((a, b)) in exact or any({a, b} <= g for g in exact):
            continue
        union = len(shingles[a] | shingles[b])
        score = len(shingles[a] & shingles[b]) / union if union else 0
        if score >= threshold:
            out.append((a, b, round(score, 2)))
    return sorted(out)


def build(root: Path, selected: list[str], cfg: dict, orphans=False, duplicates=False, policy=False,
          code_refs=False) -> dict:
    docs = discover(root, selected, cfg)
    docset = set(docs)
    stems: dict[str, list[Path]] = defaultdict(list)
    for p in docs:
        stems[p.stem.casefold()].append(p)
    errors, warnings = [], []
    if not docs:
        finding = issue('no_docs_scanned', '.', 0, 'No Markdown found; verify include patterns and doc layout')
        if selected or cfg.get('include'):
            errors.append(finding)
        else:
            warnings.append(finding)
    edges: dict[str, set[str]] = defaultdict(set)
    backlinks: dict[str, set[str]] = defaultdict(set)
    refs: dict[str, set[str]] = defaultdict(set)
    titles: dict[str, list[str]] = defaultdict(list)
    hashes: dict[str, list[str]] = defaultdict(list)
    section_hashes: dict[str, list[tuple[str, int, str]]] = defaultdict(list)
    shingles: dict[str, set[int]] = {}
    cache: dict[Path, set[str]] = {}
    content_cache: dict[Path, list[str]] = {}
    inline_cache: dict[Path, list[str]] = {}
    document_ids: dict[str, list[str]] = defaultdict(list)
    ignore_refs = cfg.get('code_ref_ignore', [])
    for p in docs:
        r = rel(p, root)
        try:
            content = p.read_text(encoding='utf-8-sig')
        except (OSError, UnicodeError) as exc:
            errors.append(issue('read_error', r, 0, str(exc)))
            continue
        lines = mask_source(content)
        content_cache[p] = lines
        inline_cache[p] = mask_source(content, keep_inline=True)
        cache[p] = heading_anchors(lines)
        if policy:
            page_warnings, doc_id = check_page_policy(root, p, content, lines, cfg)
            warnings.extend(page_warnings)
            if doc_id:
                document_ids[doc_id].append(r)
        marks = headings(lines)
        if marks and p.stem.lower() not in {'index', 'readme'}:
            titles[slug(marks[0][2])].append(r)
        body = FRONT.sub('', content.lstrip('﻿')).strip()
        if body:
            normalized = re.sub(r'\s+', ' ', body).strip().casefold()
            hashes[hashlib.sha256(normalized.encode('utf-8')).hexdigest()].append(r)
        if duplicates:
            for start, title, text in _sections(lines):
                w = words(text)
                if title and len(w) >= 40:
                    section_hashes[hashlib.sha256(' '.join(w).encode()).hexdigest()].append((r, start, title))
            w = words('\n'.join(lines))
            if len(w) >= 80:
                shingles[r] = {hash(' '.join(w[i:i + 5])) for i in range(len(w) - 4)}

    def add(source: Path, target: Path):
        if target in docset and target != source:
            a, b = rel(source, root), rel(target, root)
            edges[a].add(b)
            backlinks[b].add(a)

    for p, lines in content_cache.items():
        r = rel(p, root)
        for n, line in enumerate(lines, 1):
            for _, _, raw in link_spans(line):
                url = href(raw)
                if not url or is_remote(url):
                    continue
                parsed = urlsplit(url)
                pathname = unquote(parsed.path)
                anchor = unquote(parsed.fragment)
                if not pathname and not anchor:
                    continue
                dest = resolve(root, p, pathname) if pathname else p
                if not inside(root, dest):
                    warnings.append(issue('outside_repo', r, n, url))
                    continue
                found = existing(dest)
                if not found:
                    errors.append(issue('broken_link', r, n, url, rel(dest, root)))
                    continue
                dest = found
                if anchor and dest in cache and not has_anchor(cache[dest], anchor):
                    errors.append(issue('broken_anchor', r, n, url, rel(dest, root)))
                add(p, dest)
                if not is_doc(dest.name) and dest != root:
                    refs[r].add(rel(dest, root))
            for m in WIKILINK.finditer(line):
                expr = m.group(1).split('|', 1)[0].strip()
                name, _, anchor = expr.partition('#')
                if name == '':
                    possible = [p]
                elif '/' in name or '\\' in name:
                    name = name.replace('\\', '/')
                    dest = resolve(root, p, name)
                    candidates = [dest] if dest.suffix else [dest, dest.with_suffix('.md')]
                    possible = [x for x in candidates if x in docset]
                else:
                    possible = stems.get(Path(name).stem.casefold(), [])
                if not possible:
                    errors.append(issue('unresolved_wikilink', r, n, expr))
                elif len(possible) > 1:
                    warnings.append(issue('ambiguous_wikilink', r, n, expr, ', '.join(rel(x, root) for x in possible)))
                else:
                    dest = possible[0]
                    add(p, dest)
                    if anchor and not has_anchor(cache.get(dest, set()), anchor):
                        warnings.append(issue('unresolved_wiki_anchor', r, n, expr, rel(dest, root)))
        for n, line in enumerate(inline_cache[p], 1):
            for m in INLINE_CODE.finditer(line):
                token = looks_like_path(m.group(0).strip('`'))
                if not token or any(globmatch(token, x) for x in ignore_refs):
                    continue
                found = resolve_code_ref(root, p, token)
                if found:
                    if not is_doc(found.name):
                        refs[r].add(rel(found, root))
                elif code_refs:
                    warnings.append(issue('stale_code_ref', r, n, f'Referenced path does not exist: {token}', token))

    if policy:
        for doc_id, pages in sorted(document_ids.items()):
            if len(pages) > 1:
                warnings.append(issue('duplicate_doc_id', pages[0], 1,
                                      f'Duplicate stable id {doc_id}: ' + ', '.join(pages)))
    relationships = {rel(p, root): extract_relations(lines, p, root, docset)
                     for p, lines in content_cache.items()}
    names = {rel(p, root) for p in docs}
    declared = cfg.get('entrypoints', [])
    entrypoints = sorted(set(declared) & names) if declared else sorted(
        p for p in names if Path(p).name.lower() in ENTRY_NAMES)
    entryset = set(entrypoints)
    if declared:
        for missing in sorted(set(declared) - names):
            warnings.append(issue('missing_entrypoint', '.doc-gardener.json', 0,
                                  'Configured navigation entrypoint not scanned: ' + missing, missing))
    allowed = cfg.get('allow_orphans', [])

    def exempt(p: str) -> bool:
        return p in entryset or standalone(p) or any(globmatch(p, x) for x in allowed)

    if orphans:
        for p in sorted(names):
            if not exempt(p) and p not in backlinks:
                warnings.append(issue('orphan', p, 0, 'No incoming links from scanned documents'))
        visited = set(entrypoints)
        q = deque(entrypoints)
        while q:
            for dest in sorted(edges[q.popleft()]):
                if dest not in visited:
                    visited.add(dest)
                    q.append(dest)
        for p in sorted(names - visited):
            if not exempt(p):
                warnings.append(issue('unreachable', p, 0, 'Not reachable from configured/index entrypoints'))
        if policy and cfg.get('metadata_profile') == 'doc-gardener':
            # Index listing alone makes a page discoverable, not conceptually connected.
            for p in sorted(names - entryset):
                if any(globmatch(p, x) for x in allowed) or any(globmatch(p, x) for x in cfg.get('policy_exclude', [])):
                    continue
                inbound = set(backlinks.get(p, set()))
                if inbound and inbound <= entryset and not relationships.get(p, {}):
                    warnings.append(issue('index_only', p, 0,
                                          'Only index/entrypoint backlinks, with no typed semantic relationships'))
    if duplicates:
        for group in titles.values():
            if len(group) > 1:
                warnings.append(issue('duplicate_title', group[0], 0, 'Shared top heading: ' + ', '.join(group)))
        exact = set()
        for group in hashes.values():
            if len(group) > 1:
                exact.add(frozenset(group))
                warnings.append(issue('exact_duplicate', group[0], 0, 'Identical normalized body: ' + ', '.join(group)))
        for group in section_hashes.values():
            files = {f for f, _, _ in group}
            if len(files) > 1 and not any(files <= g for g in exact):
                where = ', '.join(f'{f}:{n} "{t}"' for f, n, t in group)
                warnings.append(issue('duplicate_section', group[0][0], group[0][1], 'Identical section text: ' + where))
        for a, b, score in _near_duplicates(shingles, exact):
            warnings.append(issue('near_duplicate', a, 0, f'Similar body ({score:.0%} shared 5-word shingles): {b}', b))
    errors.sort(key=lambda x: (x['file'], x['line'], x['type']))
    warnings.sort(key=lambda x: (x['file'], x['line'], x['type']))
    return {
        'pages_scanned': len(docs), 'entrypoints': entrypoints,
        'edges': {k: sorted(edges[k]) for k in sorted(names)},
        'backlinks': {k: sorted(backlinks[k]) for k in sorted(names)},
        'relationships': {k: relationships.get(k, {}) for k in sorted(names)},
        'code_refs': {k: sorted(refs[k]) for k in sorted(names) if refs[k]},
        'errors': errors, 'warnings': warnings,
        'limitations': 'Static Markdown approximation, not semantic truth or a complete CommonMark parser.'
    }


# ---------------------------------------------------------------- git impact

def git_changes(root: Path, base: str) -> set[str]:
    command = ['git', '-C', str(root), 'diff', '--relative', '--name-only', '-z', '--no-ext-diff', base, '--']
    ret = subprocess.run(command, capture_output=True, check=False)
    if ret.returncode:
        raise ValueError(ret.stderr.decode('utf-8', 'replace').strip() or 'git diff failed')
    changed = {p for p in ret.stdout.decode('utf-8', 'replace').split('\0') if p}
    untracked = subprocess.run(['git', '-C', str(root), 'ls-files', '--others', '--exclude-standard', '-z'],
                               capture_output=True, check=False)
    if untracked.returncode == 0:
        changed |= {p for p in untracked.stdout.decode('utf-8', 'replace').split('\0') if p and not p.endswith('/')}
    return changed


def _covers(ref: str, path: str) -> bool:
    return path == ref or path.startswith(ref.rstrip('/') + '/')


def impact(root: Path, base: str, cfg: dict, report: dict | None = None) -> dict:
    changed = git_changes(root, base)
    docs = sorted(p for p in changed if is_doc(p))
    code = sorted(p for p in changed if p not in docs)
    report = report or build(root, [], cfg)
    mapped, referencing = {}, {}
    for p in code:
        matches = sorted({q for rule in cfg.get('mappings', []) if globmatch(p, rule['code'])
                          for q in rule.get('docs', [])})
        if matches:
            mapped[p] = matches
        hits = sorted(d for d, targets in report['code_refs'].items() if any(_covers(t, p) for t in targets))
        if hits:
            referencing[p] = hits
    linking = {d: report['backlinks'][d] for d in docs if report['backlinks'].get(d)}
    return {'base': base, 'code_changes': code, 'doc_changes': docs,
            'documentation_candidates': mapped,
            'referencing_docs': referencing,
            'docs_linking_to_changed_docs': linking,
            'unrouted_code_changes': [p for p in code if p not in mapped and p not in referencing],
            'note': 'Heuristic routing: candidates to review, not proof of drift. '
                    'referencing_docs come from links and `path` mentions inside the docs.'}


def scope_to_changes(root: Path, base: str, cfg: dict, report: dict) -> dict:
    """Keep only findings relevant to files changed since base (incremental check)."""
    changed = git_changes(root, base)
    routed = impact(root, base, cfg, report)
    affected = {p for p in changed if is_doc(p)}
    for docs in routed['docs_linking_to_changed_docs'].values():
        affected.update(docs)
    for docs in routed['referencing_docs'].values():
        affected.update(docs)

    def relevant(item: dict) -> bool:
        target = item.get('target') or ''
        return item['file'] in affected or any(target == c or c.endswith('/' + target) for c in changed)

    report['errors'] = [x for x in report['errors'] if relevant(x)]
    report['warnings'] = [x for x in report['warnings'] if relevant(x)]
    report['scope'] = {'base': base, 'changed': sorted(changed), 'checked_files': sorted(affected)}
    return report


# ---------------------------------------------------------------- route (deterministic DISCOVER)

def _stem(word: str) -> str:
    return word[:max(4, len(word) - 2)] if len(word) > 5 else word


def route(root: Path, query: str, cfg: dict, limit: int = 8, selected: list[str] | None = None) -> dict:
    report = build(root, selected or [], cfg)
    q = sorted({_stem(w) for w in words(query) if w not in STOPWORDS and len(w) > 1})
    if not q:
        raise ValueError('route: query has no searchable terms')

    def hits(tokens: list[str]) -> Counter:
        c = Counter()
        for t in tokens:
            for s in q:
                if t.startswith(s):
                    c[s] += 1
        return c

    scored = []
    for name in report['edges']:
        p = root / name
        try:
            content = p.read_text(encoding='utf-8-sig')
        except (OSError, UnicodeError):
            continue
        lines = mask_source(content, keep_inline=True)
        marks = headings(lines)
        title = marks[0][2] if marks else Path(name).stem
        meta = frontmatter(content)
        path_hits = hits(words(name.replace('/', ' ')))
        title_hits = hits(words(title + ' ' + meta.get('title', '') + ' ' + meta.get('summary', '')
                                + ' ' + meta.get('description', '') + ' ' + meta.get('aliases', '')))
        head_hits = hits(words(' '.join(t for _, _, t in marks[1:])))
        body_hits = hits(words('\n'.join(lines)))
        matched = set(path_hits) | set(title_hits) | set(head_hits) | set(body_hits)
        if not matched:
            continue
        score = sum(3 * path_hits[s] + 4 * title_hits[s] + 2 * head_hits[s] + math.log1p(body_hits[s]) for s in q)
        score *= (len(matched) / len(q)) ** 2
        sections = []
        for start, heading, text in _sections(lines):
            h = hits(words(text if heading == title else heading + ' ' + text))
            if h and heading:
                end = start + text.count('\n')
                sections.append({'line': start, 'end': end, 'heading': heading,
                                 'score': round(sum(math.log1p(v) for v in h.values()) * len(h), 2)})
        sections.sort(key=lambda x: -x['score'])
        scored.append({'path': name, 'title': title, 'score': round(score, 2),
                       'matched_terms': sorted(matched), 'bytes': len(content.encode('utf-8')),
                       'approx_tokens': len(content) // 4, 'sections': sections[:3],
                       'code_refs': report['code_refs'].get(name, [])[:10]})
    scored.sort(key=lambda x: (-x['score'], x['bytes'], x['path']))
    top = scored[:limit]
    chosen = {x['path'] for x in top}
    neighbors = []
    for item in top[:3]:
        for n in report['edges'][item['path']] + report['backlinks'][item['path']]:
            if n not in chosen and n not in neighbors:
                neighbors.append(n)
    return {'query': query, 'terms': q, 'results': top, 'neighbors': neighbors[:8],
            'candidates_total': len(scored),
            'note': 'Lexical ranking. Read the top sections first; follow neighbors only if needed.'}


# ---------------------------------------------------------------- scan / init (onboarding)

def _language(sample: str) -> str:
    cyr = len(re.findall(r'[Ѐ-ӿ]', sample))
    lat = len(re.findall(r'[A-Za-z]', sample))
    cjk = len(re.findall(r'[぀-ヿ一-鿿]', sample))
    total = cyr + lat + cjk
    if not total:
        return 'unknown'
    for name, n in (('cyrillic', cyr), ('latin', lat), ('cjk', cjk)):
        if n / total > 0.75:
            return name
    return 'mixed'


def _name_style(stem: str) -> str:
    if stem.isupper() or re.fullmatch(r'[A-Z0-9_]+', stem):
        return 'UPPER'
    if re.fullmatch(r'[a-z0-9]+(-[a-z0-9]+)+', stem):
        return 'kebab-case'
    if re.fullmatch(r'[a-z0-9]+(_[a-z0-9]+)+', stem):
        return 'snake_case'
    if re.fullmatch(r'[a-z0-9]+', stem):
        return 'lowercase'
    if re.fullmatch(r'\d+[-_].+', stem):
        return 'numbered'
    return 'Mixed/Title'


def scan(root: Path, cfg: dict) -> dict:
    files = repo_files(root)
    git = git_files(root) is not None
    md = [r for r in files if is_doc(r)]
    docs = [rel(p, root) for p in discover(root, [], cfg, files)]

    agent = [f for f in AGENT_FILES if (root / f).is_file()]
    agent += sorted({d for d in AGENT_DIRS for f in files if f.startswith(d)})
    agent += sorted(f for f in md if Path(f).name in ('AGENTS.md', 'CLAUDE.md') and '/' in f)

    renderers: dict[str, list[str]] = {}
    for name, markers in RENDERERS.items():
        found = sorted({f if not m.endswith('/') else f[:f.index(m) + len(m)]
                        for f in files for m in markers
                        if (f == m or f.endswith('/' + m) or (m.endswith('/') and (f.startswith(m) or '/' + m in f)))
                        and f.count('/') <= 3})
        if name == 'sphinx':
            found = [f for f in found if 'doc' in f.lower()]
        if found:
            renderers[name] = found
    if any(Path(f).name == 'SUMMARY.md' for f in md):
        renderers.setdefault('summary-md', sorted(f for f in md if Path(f).name == 'SUMMARY.md'))

    packages = []
    for f in files:
        if Path(f).name in PACKAGE_MARKERS or f.endswith('.csproj'):
            d = Path(f).parent.as_posix()
            if any(p['dir'] == d for p in packages):
                continue
            prefix = '' if d == '.' else d + '/'
            pages = [m for m in docs if m.startswith(prefix) and (d != '.' or '/' not in m)]
            packages.append({'dir': d, 'marker': Path(f).name, 'pages': len(pages),
                             'readme': (root / prefix / 'README.md').is_file()})
    packages.sort(key=lambda x: x['dir'])

    per_dir = Counter(Path(m).parent.as_posix() for m in docs)
    doc_dirs = [{'dir': d, 'pages': n} for d, n in per_dir.most_common(30)]
    top_level = Counter(m.split('/', 1)[0] if '/' in m else '.' for m in docs)

    link_styles = Counter()
    fm_keys = Counter()
    fm_pages = 0
    rel_sections = 0
    generated, large, sample = [], [], []
    for m in docs:
        try:
            content = (root / m).read_text(encoding='utf-8-sig')
        except (OSError, UnicodeError):
            continue
        meta = frontmatter(content)
        if meta:
            fm_pages += 1
            fm_keys.update(meta.keys())
        lines = mask_source(content)
        for line in lines:
            for _, _, raw in link_spans(line):
                url = href(raw)
                if is_remote(url):
                    link_styles['external'] += 1
                elif url.startswith('/'):
                    link_styles['root_absolute'] += 1
                elif url.startswith('#'):
                    link_styles['same_page_anchor'] += 1
                elif url:
                    link_styles['relative'] += 1
            link_styles['wikilink'] += len(WIKILINK.findall(line))
            if re.match(r'^#{2,3}\s+(Relationships|Related|See also)\b', line, re.I):
                rel_sections += 1
        head = '\n'.join(content.splitlines()[:10])
        if GENERATED.search(head) or any(part in ('generated', '_generated') for part in m.split('/')):
            generated.append(m)
        n_lines = content.count('\n') + 1
        if n_lines > 600 or len(content) > 40000:
            large.append({'path': m, 'lines': n_lines, 'bytes': len(content.encode('utf-8'))})
        if len(sample) < 200:
            sample.append(content[:2000])

    health_report = build(root, [], cfg, orphans=True, duplicates=True, code_refs=True)
    health = {'errors': dict(Counter(x['type'] for x in health_report['errors'])),
              'warnings': dict(Counter(x['type'] for x in health_report['warnings'])),
              'examples': (health_report['errors'] + health_report['warnings'])[:15]}

    # ---- draft config
    exclude = set()
    for g in generated:
        parent = Path(g).parent.as_posix()
        siblings = [x for x in docs if Path(x).parent.as_posix() == parent]
        exclude.add(parent + '/**' if parent != '.' and len([x for x in siblings if x in generated]) == len(siblings) else g)
    for m in docs:
        parts = m.split('/')
        for i, part in enumerate(parts[:-1]):
            if part.lower() in FIXTURE_HINTS:
                exclude.add('/'.join(parts[:i + 1]) + '/**')
                break
    agent_tooling = sorted({d for d in AGENT_DIRS if any(m.startswith(d) for m in docs)})
    exclude.update(d + '**' for d in agent_tooling)
    allow = set()
    for m in docs:
        parts = m.split('/')
        for i, part in enumerate(parts[:-1]):
            if part.lower() in ARCHIVE_HINTS:
                allow.add('/'.join(parts[:i + 1]) + '/**')
                break
    entry = [m for m in docs if '/' not in m and Path(m).name.lower() in ('readme.md', 'agents.md')]
    for d, _ in per_dir.most_common():
        for name in ('INDEX.md', 'index.md', 'README.md', 'SUMMARY.md'):
            cand = f'{d}/{name}' if d != '.' else name
            if cand in docs and cand not in entry and not any(globmatch(cand, x) for x in exclude):
                entry.append(cand)
                break
    mappings = []
    central = {Path(m).parts[1] for m in docs if len(Path(m).parts) > 2 and Path(m).parts[0].lower() in DOC_FOLDER_HINTS}
    for pkg in packages:
        d = pkg['dir']
        if d == '.':
            continue
        targets = []
        if pkg['readme']:
            targets.append(f'{d}/README.md')
        for sub in ('docs', 'doc', 'wiki'):
            if any(m.startswith(f'{d}/{sub}/') for m in docs):
                targets.append(f'{d}/{sub}/**')
        base = Path(d).name
        for m in docs:
            parts = Path(m).parts
            if len(parts) > 2 and parts[0].lower() in DOC_FOLDER_HINTS and parts[1] == base and base in central:
                targets.append(f'{parts[0]}/{base}/**')
                break
        if targets:
            mappings.append({'code': f'{d}/**', 'docs': sorted(set(targets))})
    suggested = {'exclude': sorted(exclude), 'entrypoints': entry, 'allow_orphans': sorted(allow),
                 'metadata_profile': 'doc-gardener' if docs and fm_pages / len(docs) > 0.8 and
                 {'id', 'kind'} <= set(fm_keys) else 'none',
                 'mappings': mappings}
    suggested = {k: v for k, v in suggested.items() if v or k == 'metadata_profile'}

    # ---- open questions the agent must settle with the user (defaults are the scan's best guess)
    questions = []

    def ask(qid, question, why, default):
        questions.append({'id': qid, 'question': question, 'why': why, 'default': default})

    ask('scope', 'How far may the agent go: navigation only, moves/renames, or content restructuring too?',
        'Decides whether migration batches are allowed at all.', 'navigation only, unless the user asks for more')
    ask('audience', 'Who reads these docs: coding agents, humans, or both?',
        'Shapes index wording and page granularity.', 'both')
    lang = _language('\n'.join(sample))
    ask('language', 'Which language should new/updated docs use?', f'Detected script: {lang}.',
        {'cyrillic': 'Russian/existing', 'latin': 'English/existing'}.get(lang, 'keep existing per page'))
    if agent_tooling:
        n = sum(1 for m in docs if any(m.startswith(d) for d in agent_tooling))
        ask('agent_tooling', f'{n} pages are agent skills/rules ({", ".join(agent_tooling)}). Exclude them from the knowledge base?',
            'They configure agents rather than document the project; mixing them skews routing and orphan checks.', 'exclude')
    roots = [d for d, n in top_level.items() if n >= 3 and d != '.' and not any((d + '/').startswith(a) for a in agent_tooling)]
    if len(roots) > 1:
        ask('canonical_root', f'Several documentation areas exist ({", ".join(sorted(roots))}). Which is home for cross-cutting docs?',
            'Avoids a second parallel knowledge base.', max(roots, key=lambda d: top_level[d]))
    real_packages = [p for p in packages if p['dir'] != '.']
    if len(real_packages) > 1:
        near = sum(1 for p in real_packages if p['pages'])
        ask('placement', f'{len(real_packages)} packages found. Component docs near code (per package) or central?',
            f'{near} packages already carry their own docs.', 'near code' if near >= len(real_packages) / 2 else 'central')
    if renderers:
        ask('renderer', f'Docs renderer detected: {", ".join(renderers)}. Keep it and its navigation config authoritative?',
            'Moves must update renderer nav; links must follow renderer rules.', 'keep')
    if not docs or len(docs) < 3:
        ask('greenfield', 'Almost no docs exist. Which topics matter first (architecture, setup, decisions, operations)?',
            'Bootstrap only what has real content; no empty folders.', 'README + architecture overview + one index')
    if fm_pages and fm_pages < len(docs):
        ask('frontmatter', f'Frontmatter on {fm_pages}/{len(docs)} pages. Leave as is, or adopt consistently?',
            'Mass metadata injection is noisy; adopt only on purpose.', 'leave as is')
    if link_styles['wikilink'] and link_styles['relative']:
        ask('links', 'Both [[wiki]] and relative links are used. Standardize new links on which?',
            'Mixed styles break in renderers that support only one.',
            'wikilink' if link_styles['wikilink'] > link_styles['relative'] else 'relative')
    if generated:
        ask('generated', f'{len(generated)} pages look generated. Exclude them from checks/edits?',
            'Generated pages are rewritten by tools, not agents.', 'exclude')
    if large:
        ask('large_pages', f'{len(large)} very large pages. Split them by reader question?',
            'Large pages cost context on every read.', 'split only where sections answer separate questions')
    dup_kinds = {'exact_duplicate', 'near_duplicate', 'duplicate_section'} & set(health['warnings'])
    if dup_kinds:
        ask('duplicates', 'Duplicate content was detected. Consolidate into canonical pages?',
            'Independent copies drift.', 'review each group; merge only confirmed duplicates')
    if not agent:
        ask('activation', 'No agent instruction file (AGENTS.md/CLAUDE.md). Add the Doc Gardener rule block?',
            'Without it agents will not invoke DISCOVER/SYNC reliably.', 'add to AGENTS.md')

    return {
        'root': str(root), 'git': git, 'files_total': len(files), 'markdown_total': len(md),
        'pages_in_scope': len(docs), 'existing_config': cfg or None,
        'agent_instructions': agent, 'renderers': renderers, 'packages': packages,
        'top_level_areas': dict(top_level.most_common()), 'doc_dirs': doc_dirs,
        'conventions': {'link_styles': dict(link_styles), 'frontmatter_pages': fm_pages,
                        'frontmatter_keys': dict(fm_keys.most_common(12)),
                        'related_sections': rel_sections,
                        'filename_styles': dict(Counter(_name_style(Path(m).stem) for m in docs).most_common()),
                        'script': lang},
        'generated_candidates': generated[:50], 'large_pages': large[:30],
        'health': health, 'suggested_config': suggested, 'questions': questions,
        'note': 'Facts and a draft only. The agent decides with the user; nothing was written.'
    }


def init(root: Path, cfg: dict, write: bool, force: bool) -> dict:
    target = root / '.doc-gardener.json'
    suggested = scan(root, {})['suggested_config']
    if write:
        if target.exists() and not force:
            raise ValueError('.doc-gardener.json exists; edit it or pass --force to replace')
        target.write_text(json.dumps(suggested, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    return {'target': rel(target, root), 'write': write, 'config': suggested}


# ---------------------------------------------------------------- move (safe restructuring)

def _parse_plan(pairs: list[str], plan: Path | None) -> list[tuple[str, str]]:
    out = []
    if len(pairs) % 2:
        raise ValueError('move: give SRC DST pairs')
    out += list(zip(pairs[::2], pairs[1::2]))
    if plan:
        data = json.loads(plan.read_text(encoding='utf-8'))
        items = data.get('moves', data) if isinstance(data, dict) else data
        if isinstance(items, dict):
            out += list(items.items())
        else:
            for item in items:
                out.append((item['from'], item['to']) if isinstance(item, dict) else tuple(item))
    if not out:
        raise ValueError('move: nothing to move')
    return out


def plan_moves(root: Path, pairs: list[tuple[str, str]]) -> tuple[dict[Path, Path], list[tuple[Path, Path]]]:
    file_map: dict[Path, Path] = {}
    dir_pairs = []
    for src, dst in pairs:
        s, d = (root / src).resolve(), (root / dst).resolve()
        if not inside(root, s) or not inside(root, d) or s == root:
            raise ValueError(f'move: path outside repository: {src} -> {dst}')
        if not s.exists():
            raise ValueError(f'move: source missing: {src}')
        if s.is_dir():
            if d.exists():
                raise ValueError(f'move: destination exists: {dst}')
            dir_pairs.append((s, d))
            for base, dirs, files in os.walk(s):
                dirs[:] = [x for x in dirs if x not in SKIP]
                for f in files:
                    fp = Path(base, f)
                    file_map[fp] = d / fp.relative_to(s)
        else:
            if dst.endswith('/') or d.is_dir():
                d = d / s.name
            file_map[s] = d
    targets = Counter(file_map.values())
    for s, d in file_map.items():
        if targets[d] > 1:
            raise ValueError(f'move: two sources map to {rel(d, root)}')
        if d.exists() and d not in file_map:
            raise ValueError(f'move: destination exists: {rel(d, root)}')
        if s == d:
            raise ValueError(f'move: source equals destination: {rel(s, root)}')
    return file_map, dir_pairs


def move(root: Path, pairs: list[tuple[str, str]], apply: bool) -> dict:
    file_map, dir_pairs = plan_moves(root, pairs)

    def mapped(t: Path) -> Path:
        if t in file_map:
            return file_map[t]
        for s, d in dir_pairs:
            if t == s or s in t.parents:
                return d / t.relative_to(s)
        return t

    files = repo_files(root)
    all_docs = [(root / r).resolve() for r in files if is_doc(r)]
    all_docs += [p for p in file_map if is_doc(p.name) and p not in all_docs]
    stems: dict[str, list[Path]] = defaultdict(list)
    for p in all_docs:
        stems[p.stem.casefold()].append(p)

    def new_href(raw: str, old_src: Path, new_src: Path) -> str | None:
        url = href(raw)
        if not url or is_remote(url):
            return None
        parsed = urlsplit(url)
        if not parsed.path:
            return None
        target = resolve(root, old_src, unquote(parsed.path))
        found = existing(target)
        extensionless = found is not None and found != target
        target = found or target
        new_target = mapped(target)
        if new_target == target and new_src == old_src:
            return None
        if parsed.path.startswith('/'):
            path = '/' + rel(new_target, root)
            if extensionless:
                path = path[:-len(new_target.suffix)]
        else:
            path = os.path.relpath(new_target, new_src.parent).replace(os.sep, '/')
            if extensionless:
                path = path[:-len(new_target.suffix)]
            if parsed.path.startswith('./') and not path.startswith('.'):
                path = './' + path
        if parsed.path.endswith('/') and not path.endswith('/'):
            path += '/'
        if '%' in parsed.path or (' ' in path and not raw.strip().startswith('<')):
            path = path.replace(' ', '%20')
        idx = raw.find(parsed.path)
        if idx < 0 or path == parsed.path:
            return None
        return raw[:idx] + path + raw[idx + len(parsed.path):]

    def new_wiki(expr: str, old_src: Path, new_src: Path) -> str | None:
        name = expr.split('|', 1)[0].partition('#')[0].strip()
        if not name:
            return None
        if '/' in name:
            dest = resolve(root, old_src, name)
            candidates = [dest] if dest.suffix else [dest, dest.with_suffix('.md')]
            found = [x for x in candidates if x.exists() or x in file_map]
            if not found:
                return None
            nt = mapped(found[0])
            if nt == found[0] and new_src == old_src:
                return None
            path = '/' + rel(nt, root) if name.startswith('/') else os.path.relpath(nt, new_src.parent).replace(os.sep, '/')
            if not Path(name).suffix:
                path = path[:-len(nt.suffix)] if nt.suffix else path
        else:
            found = stems.get(Path(name).stem.casefold(), [])
            if len(found) != 1:
                return None
            nt = mapped(found[0])
            if nt.stem == found[0].stem:
                return None
            path = nt.stem
        return expr.replace(name, path, 1) if path != name else None

    def new_mention(token: str, old_src: Path) -> str | None:
        path = looks_like_path(token)
        if not path or path != token.strip().removeprefix('./'):
            return None  # keep mentions with line suffixes etc. untouched
        hit = resolve_code_ref(root, old_src, path, with_base=True)
        if not hit:
            return None
        target, base = hit
        nt = mapped(target)
        if nt == target and mapped(old_src) == old_src:
            return None
        # Keep the mention if it still resolves to the same file from the page's new location.
        anc = mapped(old_src).parent
        while True:
            if (anc / path).resolve() == nt:
                return None
            if anc == root or root not in anc.parents:
                break
            anc = anc.parent
        if base == old_src.parent and mapped(old_src) != old_src:
            base = mapped(old_src).parent
        out = os.path.relpath(nt, base).replace(os.sep, '/')
        if out.startswith('..') and not path.startswith('..'):
            out = rel(nt, root)
        if path.endswith('/'):
            out += '/'
        return ('./' if token.strip().startswith('./') else '') + out

    rewrites, new_contents = [], {}
    for p in all_docs:
        try:
            text = p.read_text(encoding='utf-8')
        except (OSError, UnicodeError):
            continue
        bom = text.startswith('﻿')
        body = text[1:] if bom else text
        src_new = mapped(p)
        lines = body.splitlines(keepends=True)
        masked = mask_source(body)
        inline = mask_source(body, keep_inline=True)
        changed = False
        for i, m in enumerate(masked):
            if i >= len(lines):
                break
            spans = []
            for start, end, raw in link_spans(m):
                nr = new_href(lines[i][start:end], p, src_new)
                if nr is not None:
                    spans.append((start, end, nr))
            for w in WIKILINK.finditer(m):
                nr = new_wiki(lines[i][w.start(1):w.end(1)], p, src_new)
                if nr is not None:
                    spans.append((w.start(1), w.end(1), nr))
            for c in INLINE_CODE.finditer(inline[i]):
                ticks = len(c.group(1))
                start, end = c.start() + ticks, c.end() - ticks
                nr = new_mention(lines[i][start:end], p)
                if nr is not None and nr != lines[i][start:end]:
                    spans.append((start, end, nr))
            if not spans:
                continue
            line = lines[i]
            for start, end, nr in sorted(spans, reverse=True):
                rewrites.append({'file': rel(src_new, root), 'line': i + 1, 'old': line[start:end], 'new': nr})
                line = line[:start] + nr + line[end:]
            lines[i] = line
            changed = True
        if changed:
            new_contents[src_new] = ('﻿' if bom else '') + ''.join(lines)
    rewrites.sort(key=lambda x: (x['file'], x['line']))

    # Non-Markdown files that mention moved paths (renderer nav, config, code comments): report only.
    moved = sorted({rel(s, root) for s in file_map if is_doc(s.name)} |
                   {rel(s, root) + '/' for s, _ in dir_pairs}, key=len, reverse=True)
    # Renderer configs often use paths relative to their docs root: also match without the first folder.
    short = sorted({m.split('/', 1)[1] for m in moved if '/' in m.rstrip('/') and len(m.split('/', 1)[1]) >= 4},
                   key=len, reverse=True)
    renderer_files = {Path(m).name for markers in RENDERERS.values() for m in markers if not m.endswith('/')}

    def mention_pattern(paths):
        return re.compile(r'(?<![\w./-])(?:' + '|'.join(re.escape(v) for v in paths) + ')') if paths else None

    full_re, short_re = mention_pattern(moved), mention_pattern(short)
    followups = []
    for r in files:
        if is_doc(r) or not full_re:
            continue
        p = root / r
        try:
            if p.stat().st_size > 1_000_000:
                continue
            text = p.read_text(encoding='utf-8')
        except (OSError, UnicodeError):
            continue
        patterns = [full_re] + ([short_re] if short_re and Path(r).name in renderer_files else [])
        for n, line in enumerate(text.splitlines(), 1):
            for pat in patterns:
                m = pat.search(line)
                if m:
                    followups.append({'file': r, 'line': n, 'mentions': m.group(0)})
                    break
    result = {'moves': [{'from': rel(s, root), 'to': rel(d, root)} for s, d in sorted(file_map.items())],
              'rewrites': rewrites, 'files_rewritten': len(new_contents),
              'manual_followups': followups[:200], 'applied': False}
    if not apply:
        result['note'] = 'Dry run. Re-run with --apply; commit before applying so the move is one reviewable diff.'
        return result

    listed = git_files(root)
    tracked = set(listed or [])
    for s, d in sorted(file_map.items()):
        d.parent.mkdir(parents=True, exist_ok=True)
        if rel(s, root) in tracked:
            subprocess.run(['git', '-C', str(root), 'mv', '-k', str(s), str(d)], check=True)
            if s.exists():  # git mv -k skips what it cannot move; fall back to a plain move
                shutil.move(str(s), str(d))
        else:
            shutil.move(str(s), str(d))
    for path, text in new_contents.items():
        path.write_text(text, encoding='utf-8')
    for s, _ in dir_pairs:  # remove source folders left empty by the move
        for base, _dirs, _files in list(os.walk(s, topdown=False)):
            try:
                Path(base).rmdir()
            except OSError:
                pass
    after = build(root, [], config(root))
    result['applied'] = True
    result['broken_after'] = [x for x in after['errors'] if x['type'] in ('broken_link', 'broken_anchor', 'unresolved_wikilink')]
    return result


