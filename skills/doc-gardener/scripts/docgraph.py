def print_scan(r: dict) -> None:
    print(f'Root: {r["root"]}  git={r["git"]}  files={r["files_total"]}  markdown={r["markdown_total"]}  in scope={r["pages_in_scope"]}')
    print('Agent instructions: ' + (', '.join(r['agent_instructions']) or '(none)'))
    print('Renderers: ' + (', '.join(f'{k} ({", ".join(v)})' for k, v in r['renderers'].items()) or '(none)'))
    if r['packages']:
        print('Packages: ' + ', '.join(f'{p["dir"]}[{p["marker"]}, {p["pages"]} docs]' for p in r['packages'][:20]))
    print('Areas: ' + ', '.join(f'{k}={v}' for k, v in r['top_level_areas'].items()))
    c = r['conventions']
    print(f'Links: {c["link_styles"]}  frontmatter pages: {c["frontmatter_pages"]}  names: {c["filename_styles"]}  script: {c["script"]}')
    if r['generated_candidates']:
        print('Generated candidates: ' + ', '.join(r['generated_candidates'][:10]))
    if r['large_pages']:
        print('Large pages: ' + ', '.join(f'{x["path"]} ({x["lines"]} lines)' for x in r['large_pages'][:10]))
    print(f'Health: errors={r["health"]["errors"]} warnings={r["health"]["warnings"]}')
    print('Suggested .doc-gardener.json:')
    print(json.dumps(r['suggested_config'], indent=2, ensure_ascii=False))
    print('Open questions:')
    for q in r['questions']:
        print(f'- [{q["id"]}] {q["question"]} (default: {q["default"]}; {q["why"]})')


def print_route(r: dict) -> None:
    print(f'Query terms: {", ".join(r["terms"])}  ({r["candidates_total"]} candidate pages)')
    for x in r['results']:
        print(f'{x["score"]:>7}  {x["path"]}  ~{x["approx_tokens"]} tok  "{x["title"]}"')
        for s in x['sections']:
            print(f'           L{s["line"]}-{s["end"]}  {s["heading"]}')
        if x['code_refs']:
            print('           code: ' + ', '.join(x['code_refs'][:5]))
    if r['neighbors']:
        print('Neighbors: ' + ', '.join(r['neighbors']))


def print_move(r: dict) -> None:
    for m in r['moves']:
        print(f'MOVE {m["from"]} -> {m["to"]}')
    for x in r['rewrites']:
        print(f'LINK {x["file"]}:{x["line"]}: {x["old"]} -> {x["new"]}')
    for x in r['manual_followups']:
        print(f'FOLLOW-UP {x["file"]}:{x["line"]}: mentions {x["mentions"]} (not changed)')
    if r['applied']:
        print(f'Applied. {len(r["broken_after"])} broken references after move.')
        for x in r['broken_after']:
            print(f'ERROR: {x["file"]}:{x["line"]}: {x["type"]}: {x["message"]}')
    else:
        print(r['note'])


def cli(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest='command', required=True)
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument('--root', default='.', type=Path)
    common.add_argument('--json', action='store_true')
    sub.add_parser('scan', parents=[common], help='Inventory + draft config + open questions')
    sp = sub.add_parser('init', parents=[common], help='Preview/write draft .doc-gardener.json')
    sp.add_argument('--write', action='store_true')
    sp.add_argument('--force', action='store_true')
    for kind in ('check', 'graph', 'route'):
        sp = sub.add_parser(kind, parents=[common])
        sp.add_argument('--docs', action='append', default=[], help='Include path/glob, repeatable')
        if kind == 'check':
            sp.add_argument('--orphans', action='store_true')
            sp.add_argument('--duplicates', action='store_true')
            sp.add_argument('--code-refs', action='store_true', help='Warn on `path/like.ext` mentions that do not exist')
            sp.add_argument('--all', action='store_true', help='--orphans --duplicates --code-refs')
            sp.add_argument('--policy', action='store_true', help='Optional metadata audit; profile is opt-in via .doc-gardener.json')
            sp.add_argument('--changed', metavar='BASE', help='Only report findings related to changes since BASE')
            sp.add_argument('--strict', action='store_true', help='Fail on warnings too')
        if kind == 'graph':
            sp.add_argument('--page', help='Relative source path to inspect')
            sp.add_argument('--format', choices=('text', 'dot', 'json'), default='text')
        if kind == 'route':
            sp.add_argument('query', nargs='+')
            sp.add_argument('--limit', type=int, default=8)
    sp = sub.add_parser('impact', parents=[common])
    sp.add_argument('--base', required=True, help='Known git revision e.g. HEAD~1')
    sp = sub.add_parser('move', parents=[common], help='Move docs and rewrite links (dry run by default)')
    sp.add_argument('pairs', nargs='*', help='SRC DST [SRC DST ...]')
    sp.add_argument('--plan', type=Path, help='JSON: {"moves": [{"from": ..., "to": ...}]}')
    sp.add_argument('--apply', action='store_true')
    sp = sub.add_parser('index', parents=[common])
    sp.add_argument('--dir', required=True, help='Documentation directory')
    sp.add_argument('--file', default='INDEX.md', help='Index filename inside --dir (e.g. README.md)')
    sp.add_argument('--write', action='store_true')
    sp.add_argument('--check', action='store_true', help='Exit 1 if the index is stale or misses pages')
    args = p.parse_args(argv)
    root = args.root.resolve()
    if not root.is_dir():
        p.error(f'No directory: {root}')
    try:
        cfg = config(root)
        if args.command == 'scan':
            result = scan(root, cfg)
        elif args.command == 'init':
            result = init(root, cfg, args.write, args.force)
        elif args.command in ('check', 'graph'):
            every = getattr(args, 'all', False)
            result = build(root, args.docs, cfg,
                           orphans=getattr(args, 'orphans', False) or every,
                           duplicates=getattr(args, 'duplicates', False) or every,
                           policy=getattr(args, 'policy', False),
                           code_refs=getattr(args, 'code_refs', False) or every)
            if getattr(args, 'changed', None):
                result = scope_to_changes(root, args.changed, cfg, result)
        elif args.command == 'route':
            result = route(root, ' '.join(args.query), cfg, args.limit, args.docs)
        elif args.command == 'impact':
            result = impact(root, args.base, cfg)
        elif args.command == 'move':
            plan = args.plan.resolve() if args.plan else None
            result = move(root, _parse_plan(args.pairs, plan), args.apply)
        else:
            result = make_index(root, args.dir, args.write, args.file, args.check)
    except (OSError, ValueError, json.JSONDecodeError, KeyError, subprocess.CalledProcessError) as exc:
        print(f'doc-gardener: {exc}', file=sys.stderr)
        return 2
    fmt = getattr(args, 'format', 'text')
    if args.command == 'graph' and args.page:
        page = args.page.removeprefix('./')
        if page not in result['edges']:
            print(f'doc-gardener: page not in scanned docs: {page}', file=sys.stderr)
            return 2
        result = {'page': page, 'outgoing': result['edges'][page], 'incoming': result['backlinks'][page],
                  'relationships': result['relationships'][page],
                  'code_refs': result['code_refs'].get(page, [])}
    if args.command == 'graph' and fmt == 'dot':
        if args.page:
            pth = result['page']
            pairs = [(pth, d) for d in result['outgoing']] + [(src, pth) for src in result['incoming']]
        else:
            pairs = [(src, dst) for src, targets in result['edges'].items() for dst in targets]
        print('digraph docs {')
        for src, dst in sorted(set(pairs)):
            print(f'  {json.dumps(src)} -> {json.dumps(dst)};')
        print('}')
    elif args.json or fmt == 'json':
        print(json.dumps(result, indent=2, ensure_ascii=False))
    elif args.command == 'check':
        for severity in ('errors', 'warnings'):
            for item in result[severity]:
                print(f'{severity[:-1].upper()}: {item["file"]}:{item["line"]}: {item["type"]}: {item["message"]}')
        scope = f'; scope: {len(result["scope"]["checked_files"])} files changed/affected since {result["scope"]["base"]}' if 'scope' in result else ''
        print(f'{result["pages_scanned"]} pages; {len(result["errors"])} errors; {len(result["warnings"])} warnings{scope}')
    elif args.command == 'graph':
        if args.page:
            print(f'Page: {result["page"]}\nIncoming: {", ".join(result["incoming"]) or "(none)"}\nOutgoing: {", ".join(result["outgoing"]) or "(none)"}\nCode refs: {", ".join(result["code_refs"]) or "(none)"}\nTyped relationships: {json.dumps(result["relationships"])}')
        else:
            print(f'Pages: {result["pages_scanned"]}; Edges: {sum(len(v) for v in result["edges"].values())}')
            for key, values in result['edges'].items():
                if values:
                    print(f'{key}: {", ".join(values)}')
    elif args.command == 'scan':
        print_scan(result)
    elif args.command == 'route':
        print_route(result)
    elif args.command == 'move':
        print_move(result)
    else:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    if args.command == 'check' and (result['errors'] or (args.strict and result['warnings'])):
        return 1
    if args.command == 'index' and args.check and not result['ok']:
        return 1
    if args.command == 'move' and result.get('broken_after'):
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(cli())
