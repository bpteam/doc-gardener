def extract_summary(p: Path) -> str:
    try:
        text = p.read_text(encoding='utf-8-sig')
    except (OSError, UnicodeError):
        return ''
    data = frontmatter(text)
    if data.get('summary') or data.get('description'):
        return (data.get('summary') or data.get('description') or '')[:140]
    plain = mask_source(text)
    for line in plain:
        line = line.strip()
        if line and not line.startswith(('#', '|', '-', '*', '>', '!', '<', '[', '=')) and len(line) > 15:
            return line[:140]
    return ''


def make_index(root: Path, dirname: str, write: bool, filename: str = 'INDEX.md', check: bool = False) -> dict:
    folder = (root / dirname).resolve()
    if not inside(root, folder) or not folder.is_dir():
        raise ValueError(f'Index directory missing or outside root: {dirname}')
    target = folder / filename
    files = sorted(p for p in folder.rglob('*') if p.is_file() and p.suffix.lower() in DOC_EXT
                   and p != target and not any(part in SKIP for part in p.relative_to(folder).parts))
    lines = []
    for p in files:
        path = p.relative_to(folder).as_posix()
        short = extract_summary(p)
        lines.append(f'- [{p.stem}]({path})' + (f' — {short}' if short else ''))
    block = '\n'.join([INDEX_START, *lines, INDEX_END])
    text = target.read_text(encoding='utf-8') if target.exists() else None
    managed = text is not None and INDEX_START in text and INDEX_END in text
    if check:
        if managed:
            start, end = text.find(INDEX_START), text.find(INDEX_END)
            stale = text[start:end + len(INDEX_END)] != block
            return {'target': rel(target, root), 'managed': True, 'stale': stale, 'ok': not stale}
        if text is None:
            return {'target': rel(target, root), 'managed': False, 'exists': False, 'ok': False,
                    'unlisted': [p.relative_to(folder).as_posix() for p in files]}
        linked = set()
        for line in mask_source(text):
            for _, _, raw in link_spans(line):
                url = href(raw)
                if url and not is_remote(url) and urlsplit(url).path:
                    linked.add(resolve(root, target, unquote(urlsplit(url).path)))
            for m in WIKILINK.finditer(line):
                linked.add(m.group(1).split('|', 1)[0].partition('#')[0].strip().casefold())
        unlisted = [p.relative_to(folder).as_posix() for p in files
                    if p.resolve() not in linked and p.stem.casefold() not in linked]
        return {'target': rel(target, root), 'managed': False, 'unlisted': unlisted, 'ok': not unlisted}
    if not write:
        return {'target': rel(target, root), 'write': False, 'pages': len(files), 'preview': block}
    if text is not None:
        start, end = text.find(INDEX_START), text.find(INDEX_END)
        if start < 0 or end < 0 or end < start:
            raise ValueError(f'Existing {rel(target, root)} has no managed markers; refusing to overwrite')
        new = text[:start] + block + text[end + len(INDEX_END):]
    else:
        new = '# Documentation index\n\n' + block + '\n'
    changed = text != new
    if changed:
        target.write_text(new, encoding='utf-8')
    return {'target': rel(target, root), 'write': True, 'pages': len(files), 'changed': changed}


